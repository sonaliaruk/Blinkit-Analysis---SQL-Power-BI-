#14. Find which product category has the most consistent sales.
-- Objective = Help to identify which item has stable demand
SELECT `year`,
       Item_Type,
       sales_stddev
FROM (
    SELECT Outlet_Establishment_Year AS `year`,
           Item_Type,
           STDDEV(Total_Sales) AS sales_stddev,
           RANK() OVER (PARTITION BY Outlet_Establishment_Year ORDER BY STDDEV(Total_Sales) asc) AS rnk
    FROM blinkit_dataset
    GROUP BY Outlet_Establishment_Year, Item_Type
) t
WHERE rnk = 1
ORDER BY `year`;
-- Across the years, Seafood ,Breakfast consistently shows the lowest variation in sales, indicating stable demand


#15. Find items that perform well in Tier 1 but poorly in Tier 3 outlets
-- Objective = Helps identify items that achieve significantly higher average sales in Tier 1 outlets compared to Tier 3 outlets, 
-- enabling targeted stocking and promotional strategies.
WITH tier_sales AS (
    SELECT Item_Type,
           Outlet_Location_Type,
           AVG(Total_Sales) AS avg_sales
    FROM blinkit_dataset
    GROUP BY Item_Type, Outlet_Location_Type
),
tier_compare AS (
    SELECT t1.Item_Type,
           t1.avg_sales AS tier1_sales,
           t3.avg_sales AS tier3_sales
    FROM tier_sales t1
    JOIN tier_sales t3 
          ON t1.Item_Type = t3.Item_Type
    WHERE t1.Outlet_Location_Type = 'Tier 1'
      AND t3.Outlet_Location_Type = 'Tier 3'
)
SELECT Item_Type, tier1_sales, tier3_sales
FROM tier_compare
WHERE tier1_sales > tier3_sales
ORDER BY (tier1_sales - tier3_sales) DESC;


-- Visibility Changes - Earlier years had higher avg_visibility (~0.09–0.12) for many products.
-- but especially in 2020–2022, visibility dropped for top-selling categories (~0.06–0.07).

-- Ratings remained stable (3.8–4.2) across all years — meaning quality perception was not a major driver of decline.

-- Possible COVID-19 Impact (2020 Onwards)
-- The drop in 2020 aligns with the COVID-19 pandemic period when: Supply chain disruptions limited stock availability.
-- In-store promotions and product visibility decreased due to lockdowns and reduced foot traffic.

-- Recovery in 2022 was partial, as volumes for many high-value categories still didn’t return to 2018 levels

